def setup_external_migrations():
    """Create external migration directories for all custom apps"""
    for app_path in CUSTOM_APPS:
        try:
            importlib.import_module(app_path)

            app_name = app_path.split(".")[-1]
            external_path = EXTERNAL_MIGRATIONS_DIR / app_name
            external_path.mkdir(parents=True, exist_ok=True)
            (external_path / "__init__.py").touch(exist_ok=True)

        except ImportError:
            continue

# Setup external migrations
